"""Export study plans to RFC 5545 iCalendar (.ics) and Markdown (.md)."""

from __future__ import annotations

from datetime import datetime, timedelta, timezone

from backend.schemas import StudyPlanResponse


def _escape_ics(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\n", "\\n")
    )


def export_plan_to_ics(plan: StudyPlanResponse) -> str:
    """Generate RFC 5545 compliant .ics calendar with non-overlapping daily study blocks."""
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//SyllabAI//Neuro-Symbolic Study Planner//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{_escape_ics(plan.metadata.course_code + ' Study Plan')}",
    ]

    # Track daily offset minutes so multiple tasks on the same day cascade cleanly
    day_cursor: dict[str, int] = {}

    for week in plan.weeks:
        for task in week.tasks:
            try:
                base_dt = datetime.strptime(task.scheduled_date, "%Y-%m-%d")
            except ValueError:
                continue

            # Start study blocks at 18:00 local time, cascading by prior blocks
            start_offset = day_cursor.get(task.scheduled_date, 18 * 60)
            start_dt = base_dt + timedelta(minutes=start_offset)
            end_dt = start_dt + timedelta(minutes=task.estimated_minutes)
            day_cursor[task.scheduled_date] = start_offset + task.estimated_minutes + 15

            desc_parts = [
                task.description,
                f"Deliverable: {task.deliverable}" if task.deliverable else "",
                f"Bloom Level: {task.bloom_level} | Type: {task.task_type}",
            ]
            if task.substeps:
                desc_parts.append("Steps:\n- " + "\n- ".join(task.substeps))

            lines.extend(
                [
                    "BEGIN:VEVENT",
                    f"UID:{task.id}-{plan.plan_id}@syllabai.local",
                    f"DTSTAMP:{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}",
                    f"DTSTART:{start_dt.strftime('%Y%m%dT%H%M%S')}",
                    f"DTEND:{end_dt.strftime('%Y%m%dT%H%M%S')}",
                    f"SUMMARY:{_escape_ics(f'[{plan.metadata.course_code}] {task.title}')}",
                    f"DESCRIPTION:{_escape_ics(chr(10).join(p for p in desc_parts if p))}",
                    f"CATEGORIES:{task.task_type.upper()},{task.bloom_level.upper()}",
                    "END:VEVENT",
                ]
            )

    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


def export_plan_to_markdown(plan: StudyPlanResponse) -> str:
    """Export a clean, recruiter/student-ready Markdown Study Guide."""
    ev = plan.evaluation
    lines = [
        f"# {plan.metadata.course_code}: {plan.metadata.course_title}",
        "",
        f"- **Generated by:** SyllabAI (`{plan.engine_used}`)",
        f"- **Timeline:** {plan.constraints.total_weeks} weeks @ {plan.constraints.weekly_hours}h/week ({plan.constraints.learning_intensity})",
        f"- **Preferred Study Days:** {', '.join(plan.constraints.preferred_days)}",
        f"- **Prerequisite Compliance:** {ev.prerequisite_compliance_rate}% | **Load Balance Score:** {ev.load_balance_score}%",
        f"- **Total Planned Hours:** {ev.total_study_hours}h | **Critical Path Topics:** {ev.critical_path_length}",
        "",
        "## Curriculum Prerequisite Graph Summary",
        "",
        "| ID | Topic | Bloom's Level | Load (1-10) | Hours | Critical Path |",
        "|---|---|---|---:|---:|:---:|",
    ]
    for t in plan.topics:
        cp = "Yes" if t.is_critical_path else "No"
        lines.append(
            f"| `{t.id}` | {t.title} | {t.bloom_level} | {t.cognitive_load} | {t.estimated_hours}h | {cp} |"
        )

    lines.extend(["", "## Weekly Study Roadmap", ""])
    for w in plan.weeks:
        badge = f" — **{w.milestone_alert}**" if w.milestone_alert else ""
        lines.append(
            f"### {w.week_label} ({w.date_range}) — {w.focus_theme}{badge}"
        )
        lines.append(
            f"*Planned: {w.planned_hours}h / {w.capacity_hours}h capacity | Avg Cognitive Load: {w.cognitive_load_avg}/10*"
        )
        lines.append("")
        for tk in w.tasks:
            check = "x" if tk.is_completed else " "
            lines.append(
                f"- [{check}] **{tk.scheduled_date} ({tk.day_label})** — **{tk.title}** "
                f"(`{tk.estimated_minutes}m`, `{tk.task_type}`, `{tk.bloom_level}`)"
            )
            if tk.deliverable:
                lines.append(f"  - *Deliverable:* {tk.deliverable}")
        lines.append("")

    return "\n".join(lines)
